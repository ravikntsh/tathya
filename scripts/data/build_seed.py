"""Build supabase/seed.sql and data/observations.csv from the data files.

Inputs: data/regions.json, data/indicators.json, data/datasets.json,
data/sources_*.json and data/series_*.csv. Checks that every row points to a
known region, indicator, dataset and source, and that no key is duplicated.
    C:\\ProgramData\\anaconda3\\python.exe -I scripts/data/build_seed.py
"""
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data"


def load(name):
    return json.loads((DATA / name).read_text(encoding="utf-8"))


def q(v):
    if v is None or v == "":
        return "null"
    return "'" + str(v).replace("'", "''") + "'"


def j(v):
    return "null" if v is None else q(json.dumps(v, ensure_ascii=False)) + "::jsonb"


regions, indicators, datasets = load("regions.json"), load("indicators.json"), load("datasets.json")
# Indicators and datasets delivered by research batches (indicators_*.json, datasets_*.json).
_ids = {i["id"] for i in indicators}
for f in sorted(DATA.glob("indicators_*.json")):
    indicators += [i for i in load(f.name) if i["id"] not in _ids and not _ids.add(i["id"])]
_ids = {d["id"] for d in datasets}
for f in sorted(DATA.glob("datasets_*.json")):
    datasets += [d for d in load(f.name) if d["id"] not in _ids and not _ids.add(d["id"])]
# Files still being researched or not yet verified stay out of the build.
PENDING = {"sources_governments.json"}
sources = [s for f in sorted(DATA.glob("sources_*.json")) if f.name not in PENDING for s in load(f.name)]

# When two files give the same key (e.g. the All-India SRS row appears both in the
# ORGI documents and in the RBI Handbook), keep the file listed first: primary
# documents before compilations. Differences in value are reported, not hidden.
PRECEDENCE = ["series_history.csv", "series_nfhs.csv", "series_national.csv", "series_state_rbi.csv"]
files = sorted(DATA.glob("series_*.csv"), key=lambda f: PRECEDENCE.index(f.name) if f.name in PRECEDENCE else 99)
rows, kept, overlaps = [], {}, []
for f in files:
    with f.open(encoding="utf-8-sig") as fh:
        for r in csv.DictReader(fh):
            key = (r["region_code"], r["indicator_id"], r["dataset_id"], r["period_label"])
            if key in kept:
                other = kept[key]
                if abs(float(other["value"]) - float(r["value"])) > 1e-9:
                    overlaps.append(f"{key}: {other['_file']}={other['value']} vs {f.name}={r['value']}")
                continue
            r["_file"] = f.name
            kept[key] = r
            rows.append(r)
if overlaps:
    print(f"{len(overlaps)} overlapping values differ (kept the first file):\n  " + "\n  ".join(overlaps), file=sys.stderr)

known = {
    "region_code": {r["code"] for r in regions},
    "indicator_id": {i["id"] for i in indicators},
    "dataset_id": {d["id"] for d in datasets},
    "source_id": {s["id"] for s in sources},
}
errors, seen = [], {}
for r in rows:
    for field, ok in known.items():
        if r[field] not in ok:
            errors.append(f"{r['_file']}: unknown {field} {r[field]!r}")
    key = (r["region_code"], r["indicator_id"], r["dataset_id"], r["period_label"])
    try:
        float(r["value"])
        int(r["year"])
    except ValueError:
        errors.append(f"{r['_file']}: bad number in {key}")
if errors:
    print("\n".join(sorted(set(errors))[:50]), file=sys.stderr)
    sys.exit(f"{len(errors)} problems; nothing written")

out = ["-- Generated by scripts/build_seed.py. Do not edit by hand.", "begin;"]
for r in regions:
    out.append(f"insert into public.regions (code, kind, name) values ({q(r['code'])}, {q(r['kind'])}, {j(r['name'])}) "
               "on conflict (code) do update set kind = excluded.kind, name = excluded.name;")
for i in indicators:
    out.append(
        "insert into public.indicators (id, label, short_label, definition, unit, dataset, higher_is_better, break_note, sort, domain, decimals, map_domain) "
        f"values ({q(i['id'])}, {j(i['label'])}, {j(i['short_label'])}, {j(i['definition'])}, {q(i['unit'])}, 'multiple', "
        f"{str(i['higher_is_better']).lower()}, {j(i.get('break_note'))}, {i['sort']}, {j(i.get('domain'))}, {i.get('decimals', 1)}, {j(i.get('map_domain'))}) "
        "on conflict (id) do update set label = excluded.label, short_label = excluded.short_label, definition = excluded.definition, "
        "unit = excluded.unit, higher_is_better = excluded.higher_is_better, break_note = excluded.break_note, sort = excluded.sort, "
        "domain = excluded.domain, decimals = excluded.decimals, map_domain = excluded.map_domain;")
for s in sources:
    out.append(
        "insert into public.sources (id, publisher, title, url, class, licence, method, coverage, limitations, last_checked) "
        f"values ({q(s['id'])}, {q(s['publisher'])}, {q(s['title'])}, {q(s['url'])}, {q(s['class'])}, {q(s.get('licence'))}, "
        f"{q(s.get('method'))}, {q(s.get('coverage'))}, {q(s.get('limitations'))}, {q(s.get('last_checked'))}) "
        "on conflict (id) do update set publisher = excluded.publisher, title = excluded.title, url = excluded.url, class = excluded.class, "
        "licence = excluded.licence, method = excluded.method, coverage = excluded.coverage, limitations = excluded.limitations, "
        "last_checked = excluded.last_checked;")
for d in datasets:
    out.append(f"insert into public.datasets (id, label, provider, class, chart) values ({q(d['id'])}, {j(d['label'])}, {q(d['provider'])}, {q(d['class'])}, {str(d.get('chart', True)).lower()}) "
               "on conflict (id) do update set label = excluded.label, provider = excluded.provider, class = excluded.class, chart = excluded.chart;")
out.append("delete from public.observations;")
cols = "region_code, indicator_id, dataset_id, period_label, year, value, source_id, source_table, source_page, date_pulled, archive_url, break_before, note"
for r in rows:
    out.append(
        f"insert into public.observations ({cols}) values ({q(r['region_code'])}, {q(r['indicator_id'])}, {q(r['dataset_id'])}, "
        f"{q(r['period_label'])}, {int(r['year'])}, {float(r['value'])}, {q(r['source_id'])}, {q(r['source_table'])}, {q(r['source_page'])}, "
        f"{q(r['date_pulled'])}, {q(r.get('archive_url'))}, {'true' if str(r['break_before']) == '1' else 'false'}, {q(r['note'])});")
out.append("commit;")
(ROOT / "supabase" / "seed.sql").write_text("\n".join(out) + "\n", encoding="utf-8")

# The same statements in parts small enough to paste into the SQL Editor: part 1
# holds reference tables and clears observations; later parts insert observations.
parts_dir = ROOT / "supabase" / "seed_parts"
parts_dir.mkdir(exist_ok=True)
for old in parts_dir.glob("*.sql"):
    old.unlink()
body = out[2:-1]
split = body.index("delete from public.observations;") + 1
chunks = [body[:split]] + [body[k:k + 600] for k in range(split, len(body), 600)]
for n, chunk in enumerate(chunks, 1):
    head = f"-- Part {n} of {len(chunks)}. Generated by scripts/data/build_seed.py. Run the parts in order."
    (parts_dir / f"seed_{n:02d}.sql").write_text("\n".join([head, "begin;", *chunk, "commit;"]) + "\n", encoding="utf-8")

# One combined file for the site's local fallback, so the page loads a single CSV.
fields = ["region_code", "indicator_id", "dataset_id", "period_label", "year", "value", "source_id",
          "source_table", "source_page", "date_pulled", "break_before", "note"]
with (DATA / "observations.csv").open("w", newline="", encoding="utf-8") as fh:
    w = csv.DictWriter(fh, fieldnames=fields, extrasaction="ignore")
    w.writeheader()
    w.writerows(rows)
(DATA / "sources.json").write_text(json.dumps(sources, indent=1, ensure_ascii=False), encoding="utf-8")
# Merged lists the site and push_supabase.py read.
(DATA / "site_indicators.json").write_text(json.dumps(indicators, indent=1, ensure_ascii=False), encoding="utf-8")
(DATA / "site_datasets.json").write_text(json.dumps(datasets, indent=1, ensure_ascii=False), encoding="utf-8")
print(f"{len(rows)} observations, {len(sources)} sources, {len(datasets)} datasets", file=sys.stderr)
