# Builds supabase/seed.sql from data/regions.json, data/indicators.json and
# data/nfhs_state.csv. Run after the data files change, then paste seed.sql into
# the Supabase SQL Editor (after migrations/0001_tracker.sql). Upserts, so it is
# safe to re-run.
#   powershell -ExecutionPolicy Bypass -File scripts/build-seed.ps1
$root = Resolve-Path (Join-Path $PSScriptRoot "..")
$utf8 = New-Object System.Text.UTF8Encoding $false

function Q($v) {
  if ($null -eq $v -or "$v" -eq "") { return "null" }
  return "'" + ("$v" -replace "'", "''") + "'"
}
function J($obj) {
  if ($null -eq $obj) { return "null" }
  return (Q ($obj | ConvertTo-Json -Compress -Depth 5)) + "::jsonb"
}
function Read-Json($rel) {
  $text = [System.IO.File]::ReadAllText((Join-Path $root $rel), [System.Text.Encoding]::UTF8)
  return $text | ConvertFrom-Json
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("-- Generated by scripts/build-seed.ps1. Do not edit by hand.")
[void]$sb.AppendLine("begin;")

foreach ($r in (Read-Json "data/regions.json")) {
  [void]$sb.AppendLine("insert into public.regions (code, kind, name) values ($(Q $r.code), $(Q $r.kind), $(J $r.name)) on conflict (code) do update set kind = excluded.kind, name = excluded.name;")
}

foreach ($i in (Read-Json "data/indicators.json")) {
  $hib = if ($i.higher_is_better) { "true" } else { "false" }
  [void]$sb.AppendLine("insert into public.indicators (id, label, short_label, definition, unit, dataset, higher_is_better, break_note, sort) values ($(Q $i.id), $(J $i.label), $(J $i.short_label), $(J $i.definition), $(Q $i.unit), $(Q $i.dataset), $hib, $(J $i.break_note), $($i.sort)) on conflict (id) do update set label = excluded.label, short_label = excluded.short_label, definition = excluded.definition, unit = excluded.unit, dataset = excluded.dataset, higher_is_better = excluded.higher_is_better, break_note = excluded.break_note, sort = excluded.sort;")
}

$csvPath = Join-Path $root "data/nfhs_state.csv"
$rows = if (Test-Path $csvPath) { Import-Csv $csvPath -Encoding UTF8 } else { @() }
foreach ($o in $rows) {
  $parts = $o.survey_years -split "-"
  $end = if ($parts.Count -eq 2) { [int]($parts[0].Substring(0, $parts[0].Length - $parts[1].Length) + $parts[1]) } else { [int]$parts[0] }
  [void]$sb.AppendLine("insert into public.observations (region_code, indicator_id, round, survey_years, period_end, value, source_url, source_page, publisher, date_pulled, archive_url, note) values ($(Q $o.state_code), $(Q $o.indicator_id), $(Q $o.round), $(Q $o.survey_years), $end, $($o.value), $(Q $o.source_url), $(Q $o.source_page), $(Q $o.publisher), $(Q $o.date_pulled), $(Q $o.archive_url), $(Q $o.note)) on conflict (region_code, indicator_id, round) do update set survey_years = excluded.survey_years, period_end = excluded.period_end, value = excluded.value, source_url = excluded.source_url, source_page = excluded.source_page, publisher = excluded.publisher, date_pulled = excluded.date_pulled, archive_url = excluded.archive_url, note = excluded.note, updated_at = now();")
}

[void]$sb.AppendLine("commit;")
$out = Join-Path $root "supabase/seed.sql"
[System.IO.File]::WriteAllText($out, $sb.ToString(), $utf8)
Write-Host "Wrote $out ($($rows.Count) observations)"
